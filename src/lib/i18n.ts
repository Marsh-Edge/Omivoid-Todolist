export type MessageKey = keyof typeof en;

export function t(
  key: MessageKey,
  params?: Record<string, string | number>,
): string {
  let value: string = en[key];
  if (params) {
    for (const [name, replacement] of Object.entries(params)) {
      value = value.replaceAll(`{${name}}`, String(replacement));
    }
  }
  return value;
}

const recurrenceFreqKeys: Record<RecurrenceFreq, MessageKey> = {
  daily: "recurrenceDaily",
  weekly: "recurrenceWeekly",
  monthly: "recurrenceMonthly",
  yearly: "recurrenceYearly",
};

const recurrenceUnitKeys: Record<RecurrenceFreq, MessageKey> = {
  daily: "recurrenceUnitDay",
  weekly: "recurrenceUnitWeek",
  monthly: "recurrenceUnitMonth",
  yearly: "recurrenceUnitYear",
};

/** Human-readable label for a stored recurrence rule ("Every 2 weeks"). */
export function recurrenceLabel(recurrence: string): string {
  const rule = parseRecurrence(recurrence);
  if (!rule) return t("recurrenceNone");
  if (rule.interval <= 1) return t(recurrenceFreqKeys[rule.freq]);
  return t("recurrenceEveryCount", {
    count: rule.interval,
    unit: t(recurrenceUnitKeys[rule.freq]),
  });
}
